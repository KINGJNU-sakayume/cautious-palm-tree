// Snapshots of the built-in catalogs that earlier versions of the app shipped.
//
// Stored state remembers which catalog it was last brought up to
// (`catalogVersion`). When a newer catalog ships, upgradeCatalog()
// (lib/appState.js) compares the stored state with the snapshot of that catalog:
//   - a built-in achievement whose fingerprint matches a shipped version was
//     never edited, so it becomes the current version (or goes away with it);
//   - a built-in achievement or default category that is in the snapshot but
//     missing from the state was deleted by the user and stays deleted;
//   - anything the snapshot doesn't have is new and gets added.
// A default category keeps the name the user gave it; one still named as in
// the snapshot takes the new default name.
//
// Changing the catalog (src/data/achievements.js, catalog/*, categories.js):
//   1. Before editing, run `npm run catalog:snapshot` and paste the snapshot
//      it prints into CATALOG_SNAPSHOTS (it is keyed by the current version).
//   2. Edit the catalog and add 1 to CATALOG_VERSION.
//   3. Run `npm run catalog:snapshot` again and copy the new digest into
//      CATALOG_DIGEST. A test fails while the digest is stale.
// Never reuse an achievement or category id for something else.

